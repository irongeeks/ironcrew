export function useCommandText() {
  const { language } = useI18n();
  return useCallback(
    (source: string): string =>
      language === "de" ? source : source.replace(/\S[\s\S]*\S|\S/, (key) => commandMessages[key] ?? key),
    [language],
  );
}

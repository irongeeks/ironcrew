import { beforeEach, afterEach, it, expect } from "vitest";
import { mkdtemp, rm, writeFile, readFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import path from "node:path";
import { list } from "tar";
import { Repository } from "../../packages/persistence/src/index.ts";
import { WebsiteWorkflow } from "../../packages/domain/workflows/website.ts";
import { siteProject, buildSiteProject } from "../../packages/tools/site-build.ts";
import type { Scope } from "../../packages/contracts/src/index.ts";
let directory: string, repo: Repository, scope: Scope;
beforeEach(async () => {
  directory = await mkdtemp(path.join(tmpdir(), "site-package-test-"));
  repo = await Repository.open(path.join(directory, "company.sqlite"));
  const setup = await repo.setup({
    companyName: "Package fixture",
    ceoName: "CEO",
    passwordHash: "fixture",
    timezone: "UTC",
    budgetLimitUsdMicros: "0",
  });
  scope = { companyId: setup.company.id, areaId: setup.areas[0]!.id };
});
afterEach(async () => {
  await repo.close();
  await rm(directory, { recursive: true, force: true });
});
it("exports all manifest files deterministically and refuses changed source or preview bytes", async () => {
  const order = await repo.createOrder(scope, { kind: "website", goal: "Selfhosting", budgetLimitUsdMicros: "0" }),
    web = new WebsiteWorkflow(repo, directory);
  await web.create(scope, order.id, "Package test");
  const concepts = await web.concepts(scope, order.id, [
    {
      name: "A",
      rationale: "A",
      html: '<h1>Package source</h1><img src="/missing" onerror="alert(1)"><script>alert(1)</script>',
    },
    { name: "B", rationale: "B", html: "<h1>Other</h1>" },
  ]);
  await web.select(scope, order.id, concepts.data.concepts[0]!.id);
  const artifact = await web.build(scope, order.id),
    first = await web.packageArchive(scope, artifact.id),
    second = await web.packageArchive(scope, artifact.id);
  expect(first.sha256).toBe(second.sha256);
  expect(first.packageSha256).toBe(artifact.packageSha256);
  const archive = path.join(directory, "site.tgz");
  await writeFile(archive, first.content);
  const files: string[] = [];
  await list({
    file: archive,
    onReadEntry: (entry) => {
      files.push(entry.path);
    },
  });
  expect(files.sort()).toEqual(["README.md", "index.html", "server.mjs"]);
  await expect(web.previewAsset(artifact.id, "../company.sqlite")).rejects.toMatchObject({
    code: "preview_path_denied",
  });
  await expect(web.previewAsset(artifact.id, "README.md")).rejects.toMatchObject({ code: "preview_path_denied" });
  const html = path.join(directory, "sites", artifact.id, "index.html");
  const publishedHtml = await readFile(html, "utf8");
  expect(publishedHtml).toContain('http-equiv="Content-Security-Policy"');
  expect(publishedHtml).not.toMatch(/onerror=|<script/i);
  expect(await readFile(path.join(directory, "sites", artifact.id, "server.mjs"), "utf8")).toContain(
    "Content-Security-Policy",
  );
  await writeFile(html, "changed");
  await expect(web.preview(artifact.id)).rejects.toMatchObject({ code: "artifact_corrupt" });
  await expect(web.packageArchive(scope, artifact.id)).rejects.toMatchObject({ code: "artifact_corrupt" });
});
it("creates offline pinned React and standard WordPress sources while rejecting a fake execution port", async () => {
  const react = await siteProject("react", "<h1>React source</h1><script>window.injected=true</script>");
  expect(react["src/concept.mjs"]).toContain("React source");
  expect(react["src/app.mjs"]).toContain("createRoot");
  expect(react["vendor/LICENSE.txt"]).toContain("MIT");
  expect(JSON.parse(react["vendor/manifest.json"]!).react).toBe("19.2.7");
  const wordpress = await siteProject(
    "wordpress",
    "<html><head><style>h1{color:red}</style></head><body><h1>WP source</h1></body></html>",
  );
  expect(wordpress["theme/templates/index.html"]).toBe("<!-- wp:html -->\n<h1>WP source</h1>\n<!-- /wp:html -->\n");
  expect(wordpress["theme/style.css"]).toContain("h1{color:red}");
  expect(wordpress["theme/functions.php"]).toContain("wp_enqueue_style");
  await expect(siteProject("wordpress", "<?php system('bad'); ?>")).rejects.toMatchObject({
    code: "php_in_concept_denied",
  });
  await expect(
    buildSiteProject(directory, "react", {
      execute: async () => {
        throw new Error("must not execute");
      },
    }),
  ).rejects.toMatchObject({ code: "isolation_attestation_required" });
});
